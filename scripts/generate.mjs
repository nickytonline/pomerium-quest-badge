// Turns the browser game's source into the badge's data, so policies, signs, books, letters and the map
// can't drift from Pomerium Quest. Also writes the browser evaluator's decisions as test fixtures, which
// the Python tests check the badge's port against.
//
// Run: node scripts/generate.mjs   (QUEST_DIR points at a Pomerium Quest checkout; default ../pomerium-quest)
import { copyFileSync, mkdirSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'

const root = resolve(import.meta.dirname, '..')
const quest = resolve(process.env.QUEST_DIR ?? join(root, '..', 'pomerium-quest'))
const game = join(quest, 'app', 'src', 'game')
const load = (name) => import(join(game, name))

const { ZONES } = await load('zones.ts')
const { GROUPS } = await load('groups.ts')
const world = await load('world.ts')
const content = await load('content.ts')
const house = await load('house.ts')
const ppl = await load('ppl.ts')
const { KNIGHT_QUOTA } = await load('quest-machine.ts')

/** The host and upstream the browser game's signs show; the badge shows the same route config. */
const HOST = 'game.localhost.pomerium.io'
const UPSTREAM = 'http://quest.quest.svc.cluster.local:3000'

/** A JSON value as a Python literal. */
function py(value, indent = 0) {
  const pad = ' '.repeat(indent)
  const inner = ' '.repeat(indent + 4)

  if (value === null || value === undefined) return 'None'

  if (value === true) return 'True'

  if (value === false) return 'False'

  if (typeof value === 'number') return String(value)

  if (typeof value === 'string') return JSON.stringify(value)

  if (Array.isArray(value)) {
    if (value.length === 0) return '()'

    const items = value.map((item) => inner + py(item, indent + 4))

    return `(\n${items.join(',\n')},\n${pad})`
  }

  const entries = Object.entries(value).map(([key, item]) => `${inner}${JSON.stringify(key)}: ${py(item, indent + 4)}`)

  return entries.length ? `{\n${entries.join(',\n')},\n${pad}}` : '{}'
}

const criterion = (node) => {
  const { kind, ...rest } = node

  return { kind, ...rest }
}

const policy = (rules) => rules.map((rule) => ({ ...rule, criteria: rule.criteria.map(criterion) }))

const built = world.buildWorld()

const data = {
  GROUPS,
  KNIGHT_QUOTA,
  HOST,
  ZONES: ZONES.map((zone) => ({ ...zone, policy: policy(zone.policy) })),
  ROUTE_YAML: Object.fromEntries(ZONES.map((zone) => [zone.id, ppl.routeYaml(zone, HOST, UPSTREAM).split('\n')])),
  SIGN_TEXT: content.SIGN_TEXT,
  SIGN_DOCS: content.SIGN_DOCS,
  LESSONS: content.LESSONS,
  LESSON_ORDER: content.LESSON_ORDER,
  STALE_DOCS: content.STALE_DOCS,
  BOOKS: content.BOOKS,
  LETTERS: content.LETTERS,
  LETTER_ORDER: Object.keys(content.LETTERS),
  VISITORS: house.VISITORS,
  TOWNSFOLK_DOMAIN: house.TOWNSFOLK_DOMAIN,
  HOUSE_PREFIX: house.HOUSE_PREFIX,
  TILE: world.TILE,
  FOUNTAIN_FRAMES: world.FOUNTAIN_FRAMES,
  WALKABLE: [...world.WALKABLE],
  PLAYER_TERRAIN: [...world.PLAYER_TERRAIN],
  MAP_WIDTH: world.MAP_WIDTH,
  MAP_HEIGHT: world.MAP_HEIGHT,
  TILE_PX: world.TILE_PX,
  NPC_FRAME: world.NPC_FRAME,
  PHISH_FRAME: world.PHISH_FRAME,
  GUARD_FRAME: world.GUARD_FRAME,
  HOUSE: world.HOUSE,
  MAP: built.tiles,
  GATES: built.gates,
  SIGNS: built.signs,
  NPCS: built.npcs,
  BOTS: built.bots,
  PHISH: built.phish,
  ROCKS: built.rocks,
  CHEST: built.chest,
  FOUNTAIN: built.fountain,
  SPAWN: built.spawn,
}

const header = [
  '# Generated by scripts/generate.mjs from Pomerium Quest. Do not edit: change the browser game and run it again.',
  '# fmt: off',
  '',
]

// One map row per line, as bytes: compact to read here, and light for MicroPython to load.
const mapRows = (rows) => `(\n${rows.map((row) => `    bytes((${row.join(', ')})),`).join('\n')}\n)`
const body = Object.entries(data).map(([name, value]) => `${name} = ${name === 'MAP' ? mapRows(value) : py(value)}\n`)
const app = join(root, 'badge', 'pomerium_quest')
writeFileSync(join(app, 'data.py'), header.join('\n') + body.join('\n'))

// The sprite sheets are already 16px pixel art: the badge draws them as they are.
mkdirSync(join(app, 'assets'), { recursive: true })

for (const sheet of ['dog.png', 'items.png', 'npcs.png', 'tiles.png'])
  copyFileSync(join(quest, 'app', 'public', 'assets', sheet), join(app, 'assets', sheet))

// Every zone asked by a range of identities and both methods, decided by the browser game's evaluator.
const identities = [
  { authenticated: false, email: '', groups: [] },
  { authenticated: true, email: 'wanderer@outlands.net', groups: [] },
  { authenticated: true, email: 'you@quest.example', groups: [GROUPS.citizens], deed: 'house-1' },
  { authenticated: true, email: 'you@quest.example', groups: [GROUPS.citizens, GROUPS.knights] },
  { authenticated: true, email: 'you@quest.example', groups: [GROUPS.citizens, GROUPS.scholars] },
  { authenticated: true, email: 'you@quest.example', groups: [GROUPS.citizens, GROUPS.knights, GROUPS.scholars] },
  { authenticated: true, email: 'scribe@quest.example', groups: [GROUPS.citizens, GROUPS.scribes] },
]

const houseRules = [
  house.deedRule('house-1'),
  { action: 'allow', match: 'or', criteria: [{ kind: 'email', is: 'wanderer@outlands.net' }] },
  { action: 'deny', match: 'or', criteria: [{ kind: 'email', is: `baker@${house.TOWNSFOLK_DOMAIN}` }] },
  { action: 'allow', match: 'and', criteria: [{ kind: 'claim', claim: 'groups', value: 'knights' }, { kind: 'http_method', is: 'GET' }] },
  { action: 'allow', match: 'not', criteria: [{ kind: 'domain', is: house.TOWNSFOLK_DOMAIN }] },
  { action: 'allow', match: 'or', criteria: [{ kind: 'accept' }] },
]

const policed = [
  ...ZONES.map((zone) => ({ name: zone.id, policy: zone.policy })),
  ...houseRules.map((rule, index) => ({ name: `house-${index}`, policy: [houseRules[0], rule] })),
]

const fixtures = policed.flatMap(({ name, policy: rules }) =>
  identities.flatMap((id) =>
    ['GET', 'POST'].flatMap((method) =>
      ['your', 'their'].map((whose) => {
        const decision = ppl.decide({ policy: rules }, id, { method, path: '/' }, whose)

        return { name, policy: policy(rules), id, method, whose, allow: decision.allow, lines: decision.lines }
      }),
    ),
  ),
)

mkdirSync(join(root, 'tests', 'fixtures'), { recursive: true })
writeFileSync(join(root, 'tests', 'fixtures', 'decisions.json'), JSON.stringify(fixtures) + '\n')

console.log(`Wrote data.py, ${fixtures.length} decisions and the sprite sheets from ${quest}`)
