/** A JSON value as a Python literal. */
function py(value, indent = 0) {
  const pad = ' '.repeat(indent)
  const inner = ' '.repeat(indent + 4)

  if (value === null || value === undefined) return 'None'

  if (value === true) return 'True'

  if (value === false) return 'False'

  if (typeof value === 'number') return String(value)

  if (typeof value === 'string') return JSON.stringify(value)

  if (Array.isArray(value)) {
    if (value.length === 0) return '()'

    const items = value.map((item) => inner + py(item, indent + 4))

    return `(\n${items.join(',\n')},\n${pad})`
  }

  const entries = Object.entries(value).map(([key, item]) => `${inner}${JSON.stringify(key)}: ${py(item, indent + 4)}`)

  return entries.length ? `{\n${entries.join(',\n')},\n${pad}}` : '{}'
}

